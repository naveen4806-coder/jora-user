import http from 'node:http';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { connectDatabase } from '../config/db.js';
import { env } from '../config/env.js';
import { errorHandler, notFound } from '../middleware/errors.js';
import authRoutes from '../routes/auth.js';
import catalogRoutes from '../routes/catalog.js';
import orderRoutes from '../routes/orders.js';
import vendorRoutes from '../routes/vendor.js';
import partnerRoutes from '../routes/partner.js';
import adminRoutes from '../routes/admin.js';
import supportRoutes from '../routes/support.js';
import trackingRoutes from '../routes/tracking.js';
import { createSocketServer } from '../sockets/index.js';

const app = express();
const server = http.createServer(app);
const io = createSocketServer(server);
app.set('io', io);
app.use(helmet());
app.use(cors({ origin: env.clientOrigins, credentials: false }));
app.use(express.json({ limit: '1mb' }));
app.use(morgan('dev'));
app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false }), authRoutes);
app.get('/api/health', (_req, res) => res.json({ ok: true, service: 'jora-api' }));
app.use('/api/catalog', catalogRoutes);
app.use('/api/orders', orderRoutes);
app.use('/api/vendor', vendorRoutes);
app.use('/api/partner', partnerRoutes);
app.use('/api/admin', adminRoutes);
app.use('/api', supportRoutes);
app.use('/api', trackingRoutes);
app.use(notFound);
app.use(errorHandler);

await connectDatabase();
server.listen(env.port, () => console.log(`Jora Mongo API listening on ${env.port}`));
